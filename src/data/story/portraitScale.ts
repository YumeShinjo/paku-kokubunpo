/**
 * 立ち絵の表示倍率(複数人の場面)。
 * 同じ場面に2人以上の立ち絵が出るときは、全員を小さくして、画面の狭い端末でも、並んだ2人が重ならず、
 * 見切れないようにする。1人だけの場面は、いつも 1 倍(この設定の対象外)。
 * 足元の位置と、左右の置き場は変えない(足元を原点に、縮めるだけ。global.css の --portrait-scale)。
 * 倍率を直したいときは、ここだけを直せばよい。実機での見え方(2人の大きさのバランス)で決めた値。
 */

/** 2人以上のときの、全員に掛ける倍率(1人のときの約78%) */
export const MULTI_SCALE = 0.78;

/**
 * 2人以上のとき、キャラごとに、さらに掛ける補正(1=補正なし。キーは data/story/characterFacing.ts と同じ)。
 * 立ち絵の画像ごとに、キャンバスに対するキャラクターの大きさが違うので、並べたときのバランスをここで整える。
 * コレット(本来の姿)は、1人のときに大きく見せるため、専用の大きな枠で表示している。
 * 王様と並ぶ場面では、王様を約8%大きくし、コレットは、見えている高さが王様の約85%になるよう下げる。
 * (コレットは頭が大きく、ドレスも横に広いので、高さが同じでも大きく見える。高さを低めにして、見た目を合わせる)
 */
export const MULTI_SCALE_ADJUST: Readonly<Record<string, number>> = {
  ヴェルバルト: 1.08,
  コレット: 0.825,
};

/** 複数人の場面での、そのキャラクターの表示倍率 */
export function multiScaleFor(key: string): number {
  return MULTI_SCALE * (MULTI_SCALE_ADJUST[key] ?? 1);
}
