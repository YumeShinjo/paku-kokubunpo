import { choiceQ, createChoiceArranger } from "@/data/questionBuilders";
import type { ChoiceQuestion } from "@/data/schema";

const arrange = createChoiceArranger();

/**
 * 敬語(場面説明付き選択式)。場面を situation、出題を prompt に置く。
 * 単元は4つ: 尊敬語(sonkeigo)・謙譲語(kenjougo)・丁寧語(teineigo)・敬語の識別(keigo-shikibetsu)。
 * 誤用の発見・敬語の種類識別は問題数が少ないため、「敬語の識別」にまとめている。
 * 丁寧語は追加出題データ(2026年9月分)で新設した単元。
 */
function make(prefix: string, unit: string) {
  return (
    n: number,
    scene: string,
    prompt: string,
    correct: string,
    wrongs: string[],
    explanation: string,
  ): ChoiceQuestion => {
    const { choices, correctIndex } = arrange(correct, wrongs);
    return choiceQ({
      id: `ohza-${prefix}-${String(n).padStart(2, "0")}`,
      unit,
      prompt,
      situation: `場面: ${scene}`,
      choices,
      correctIndex,
      explanation,
      autoRuby: true,
    });
  };
}

