import { fillBlankQ } from "@/data/questionBuilders";
import type { AssemblyQuestion } from "@/data/schema";

const UNIT = "doushi-katsuyoukei";

function q(
  id: string,
  baseVerb: string,
  sentenceTemplate: string,
  cards: string[],
  correctIndex: number,
  katsuyokei: string,
  explanation: string,
): AssemblyQuestion {
  return fillBlankQ({
    id,
    unit: UNIT,
    instruction: `「${baseVerb}」を、空欄に当てはまる形にして文を完成させましょう。`,
    sentenceTemplate,
    cards,
    correctIndex,
    explanation,
    tags: [katsuyokei],
  });
}

