import { choiceQ } from "@/data/questionBuilders";
import type { ChoiceQuestion } from "@/data/schema";

const UNIT = "doushi-katsuyou-shurui";
const PROMPT_PREFIX = "「%」の空欄にあてはまる音を選び、活用の種類を確かめましょう。";

function q(
  id: string,
  word: string,
  situation: string,
  choices: string[],
  correctIndex: number,
  katsuyouShurui: string,
  point: string,
  explanation: string,
  /** 問いの文を、既定の「空欄にあてはまる音を選ぶ」形から変えたいとき(カ変「来る」など、読みそのものが変わる動詞) */
  prompt?: string,
): ChoiceQuestion {
  return choiceQ({
    id,
    unit: UNIT,
    prompt: prompt ?? PROMPT_PREFIX.replace("%", word),
    situation,
    choices,
    correctIndex,
    explanation: `${explanation}(${katsuyouShurui}: ${point})`,
    tags: [katsuyouShurui],
  });
}

