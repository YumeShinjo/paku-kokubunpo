import { fillBlankQ } from "@/data/questionBuilders";
import type { AssemblyQuestion } from "@/data/schema";

const UNIT = "keiyoudoushi-katsuyou";

function q(
  id: string,
  word: string,
  sentenceTemplate: string,
  cards: string[],
  correctIndex: number,
  katsuyokei: string,
  explanation: string,
): AssemblyQuestion {
  return fillBlankQ({
    id,
    unit: UNIT,
    instruction: `「${word}」を、空欄に当てはまる形にして文を完成させましょう。`,
    sentenceTemplate,
    cards,
    correctIndex,
    explanation,
    tags: [katsuyokei],
  });
}

