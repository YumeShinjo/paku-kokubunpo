import { choiceQ } from "@/data/questionBuilders";
import type { ChoiceQuestion } from "@/data/schema";

const UNIT = "katsuyou-umu";
const PROMPT_PREFIX = "文中の「%」は活用する・活用しないのどちらでしょう。";
const CHOICES = ["活用する", "活用しない"];

function q(
  id: string,
  target: string,
  situation: string,
  correctIndex: 0 | 1,
  explanation: string,
  hint?: string,
): ChoiceQuestion {
  return choiceQ({
    id,
    unit: UNIT,
    prompt: PROMPT_PREFIX.replace("%", target),
    situation,
    choices: CHOICES,
    correctIndex,
    explanation: hint ? `${explanation}(まちがえやすいポイント: ${hint})` : explanation,
    tags: [correctIndex === 0 ? "活用する" : "活用しない"],
  });
}

