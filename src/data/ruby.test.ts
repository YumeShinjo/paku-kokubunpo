import { describe, expect, it } from "vitest";
import { rb } from "./ruby";

describe("rb", () => {
  it("ふりがな指定がなければ1セグメントのプレーンテキストになる", () => {
    expect(rb("これはテストです。")).toEqual([{ text: "これはテストです。" }]);
  });

  it("漢字[ふりがな]をルビ付きセグメントに変換する", () => {
    expect(rb("次の単語を、正しい品詞[ひんし]のカゴに分けましょう。")).toEqual([
      { text: "次の単語を、正しい" },
      { text: "品詞", ruby: "ひんし" },
      { text: "のカゴに分けましょう。" },
    ]);
  });

  it("複数のルビ指定を含む文を変換できる", () => {
    expect(rb("自立語[じりつご]と付属語[ふぞくご]に分けましょう。")).toEqual([
      { text: "自立語", ruby: "じりつご" },
      { text: "と" },
      { text: "付属語", ruby: "ふぞくご" },
      { text: "に分けましょう。" },
    ]);
  });

  it("先頭がルビ指定の場合も正しく変換する", () => {
    expect(rb("未然形[みぜんけい]を選びましょう。")).toEqual([
      { text: "未然形", ruby: "みぜんけい" },
      { text: "を選びましょう。" },
    ]);
  });

  it("末尾がルビ指定の場合も正しく変換する", () => {
    expect(rb("これは体言[たいげん]")).toEqual([
      { text: "これは" },
      { text: "体言", ruby: "たいげん" },
    ]);
  });

  it("空欄マーカー___を独立したセグメントに分割する(AssemblyEngineが検出できるようにするため)", () => {
    expect(rb("手紙を___ない。")).toEqual([
      { text: "手紙を" },
      { text: "___" },
      { text: "ない。" },
    ]);
  });

  it("空欄マーカーが先頭にある場合も正しく分割する", () => {
    expect(rb("___ない")).toEqual([{ text: "___" }, { text: "ない" }]);
  });
});
